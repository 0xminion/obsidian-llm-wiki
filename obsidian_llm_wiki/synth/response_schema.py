"""Canonical single-pass wire schema matching ``prompts.SYNTHESIS_SCHEMA``.

Strict structured-output providers require every object to be closed and every
property to be required, including objects inside arrays. Required *keys* do not
require invented information: optional lists may be empty and optional strings
use "" (the parser's existing representation), not null. Completed-body, source
faithfulness, identity and evidence checks still belong to ``validate_synthesis``.

This is the model's output contract, not the cache serialization format. Source
hashes, evidence offsets and verification flags are resolved by the application;
they must not be generated by the model.
"""

from __future__ import annotations

from typing import Any

from obsidian_llm_wiki.core.models import VALID_RELATIONS, ProvenanceState


def _object(properties: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def _array(items: dict[str, Any]) -> dict[str, Any]:
    return {"type": "array", "items": items}


SYNTHESIS_RESPONSE_SCHEMA: dict[str, Any] = _object({
    "source_title": {"type": "string"},
    "source_summary": {"type": "string"},
    "source_tags": _array({"type": "string"}),
    "key_points": _array({"type": "string"}),
    "open_questions": _array({"type": "string"}),
    "language": {"type": "string"},
    "concepts": _array(_object({
        "title": {"type": "string"},
        "slug": {"type": "string"},
        "canonical_id": {
            "type": "string",
            "description": "Exact supplied candidate ID when reused; empty for a new concept.",
        },
        "summary": {"type": "string"},
        "tags": _array({"type": "string"}),
        "aliases": _array({"type": "string"}),
        "sections": _array(_object({
            "heading": {"type": "string"},
            "points": _array({"type": "string"}),
            "prose": {
                "type": "string",
                "description": "Flowing prose, or empty when points supply the section content.",
            },
        })),
        "claims": _array(_object({
            "text": {"type": "string"},
            "quote": {"type": "string"},
            "source_ref": {
                "type": "string",
                "description": "Location in the source if known; otherwise empty.",
            },
        })),
        "related": _array(_object({
            "slug": {"type": "string"},
            "relation": {"type": "string", "enum": sorted(VALID_RELATIONS)},
            "display": {
                "type": "string",
                "description": "Optional link display text; empty when not needed.",
            },
        })),
        "confidence": {"type": "number", "minimum": 0, "maximum": 1},
        "provenance": {"type": "string", "enum": [state.value for state in ProvenanceState]},
        "is_new": {"type": "boolean"},
    })),
    "maps": _array(_object({
        "title": {"type": "string"},
        "slug": {"type": "string"},
        "summary": {"type": "string"},
        "tags": _array({"type": "string"}),
        "concept_slugs": _array({"type": "string"}),
    })),
})
